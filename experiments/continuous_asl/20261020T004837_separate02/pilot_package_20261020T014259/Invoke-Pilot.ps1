param(
 [ValidateSet('Verify','DryRun','Tests','Protocol','ValidateReal')][string]$Phase='Verify',
 [string]$Manifest,
 [string]$DataRoot,
 [ValidateSet('first','second')][string]$Stage='first'
)
$ErrorActionPreference='Stop'
$pilotRoot=$PSScriptRoot
$repo=(Get-Item -LiteralPath $pilotRoot).Parent.Parent.Parent.Parent.FullName
$python=Join-Path $repo 'experiments/continuous_asl/20261019T155428Z_cslr01/runtime/venv/Scripts/python.exe'
function New-PilotRun([string]$Prefix){
 $target=Join-Path $pilotRoot ('runs/'+$Prefix+'_'+(Get-Date -Format 'yyyyMMddTHHmmss_fff'))
 New-Item -ItemType Directory -Path $target -ErrorAction Stop | Out-Null
 return $target
}
switch($Phase){
 'Verify' {
  $hashes=Get-Content -LiteralPath (Join-Path $pilotRoot 'artifact_hashes.json') -Raw | ConvertFrom-Json
  foreach($item in $hashes.files){
   $actual=(Get-FileHash -LiteralPath (Join-Path $pilotRoot $item.path) -Algorithm SHA256).Hash.ToLowerInvariant()
   if($actual -ne $item.sha256){throw "PILOT_ARTIFACT_HASH_MISMATCH: $($item.path)"}
  }
  [PSCustomObject]@{status='PASS_PACKAGE_INTEGRITY';files=$hashes.files.Count;training='BLOCKED';real_signer_validated=$false} | ConvertTo-Json
 }
 'Protocol' {Get-Content -LiteralPath (Join-Path $pilotRoot 'recording_protocol.md')}
 'DryRun' {
  $output=New-PilotRun 'synthetic'
  foreach($case in @('first','second')){
   $bundle=Join-Path $output $case
   & $python -B (Join-Path $pilotRoot 'synthetic_fixture.py') --out $bundle --stage $case *> (Join-Path $output ($case+'_build.txt'))
   if($LASTEXITCODE -ne 0){throw "SYNTHETIC_BUILD_EXIT_$LASTEXITCODE"}
   & $python -B (Join-Path $pilotRoot 'validate_pilot.py') --manifest (Join-Path $bundle 'manifest.json') --data-root $bundle --stage $case --synthetic --report (Join-Path $output ($case+'_validation.json')) *> (Join-Path $output ($case+'_validation.txt'))
   if($LASTEXITCODE -ne 0){throw "SYNTHETIC_VALIDATE_EXIT_$LASTEXITCODE"}
   Get-Content -LiteralPath (Join-Path $output ($case+'_validation.json')) -Raw
  }
  Write-Output "SYNTHETIC_ONLY_OUTPUT: $output"
 }
 'Tests' {
  $output=New-PilotRun 'tests'
  $junitPath=Join-Path $output 'tests.xml'
  & $python -B -m pytest (Join-Path $pilotRoot 'test_validator.py') -q --tb=short -p no:cacheprovider ("--junitxml="+$junitPath) *> (Join-Path $output 'tests.txt')
  $resultCode=$LASTEXITCODE
  Get-Content -LiteralPath (Join-Path $output 'tests.txt') -Tail 15
  if($resultCode -ne 0){throw "PILOT_TEST_EXIT_$resultCode"}
 }
 'ValidateReal' {
  if(-not $Manifest -or -not $DataRoot){throw 'Provide real private -Manifest and -DataRoot only AFTER human permission review; neither is generated by this script.'}
  & $python -B (Join-Path $pilotRoot 'validate_pilot.py') --manifest $Manifest --data-root $DataRoot --stage $Stage
  if($LASTEXITCODE -ne 0){throw "REAL_INTAKE_BLOCKED_OR_REJECTED_EXIT_$LASTEXITCODE"}
 }
}
